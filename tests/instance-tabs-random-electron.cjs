'use strict';
const { app, BrowserWindow, shell } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');
const http = require('node:http');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'arena-tabs-random-electron-'));
app.setPath('userData', root);
app.commandLine.appendSwitch('disable-gpu');
app.commandLine.appendSwitch('disable-features', 'CalculateNativeWinOcclusion');
const { Controller } = require('../src/main/controller.cjs');
const { installIPC } = require('../src/main/ipc.cjs');
const { Store } = require('../src/main/store.cjs');
const openedExternal = [];
shell.openExternal = async url => { openedExternal.push(url); };
const wait = async (predicate, label, limit = 160) => { for (let i = 0; i < limit; i++) { if (await predicate()) return; await new Promise(resolve => setTimeout(resolve, 50)); } throw Error(`Timeout: ${label}`); };
let window, controller, server;
app.whenReady().then(async () => {
  try {
    server = http.createServer((_req, res) => { res.setHeader('Content-Type', 'text/html; charset=utf-8'); res.end('<!doctype html><title>Environment verification</title><h1>Local environment verification</h1>'); });
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
    const url = `http://127.0.0.1:${server.address().port}/`;
    window = new BrowserWindow({ show: false, width: 1440, height: 900, webPreferences: { preload: path.join(__dirname, '../src/main/preload.cjs'), sandbox: true, nodeIntegration: false, contextIsolation: true, backgroundThrottling: false } });
    controller = new Controller(window, root, path.join(root, 'mihomo-not-required'));
    for (let i = controller.store.list().length; i < 8; i++) controller.store.create(`实例 ${i + 1}`);
    for (const instance of controller.store.list()) { controller.store.update(instance.id, { url }); await controller.start(instance.id); }
    installIPC(window, controller);
    await window.loadFile(path.join(__dirname, '../src/renderer/index.html'));
    const ui = code => window.webContents.executeJavaScript(code);
    await wait(() => ui('typeof route === "function" && !!document.querySelector("#tabs")'), 'renderer');
    await ui("route('overview')");
    await wait(() => ui('document.querySelectorAll("#tabs [data-tab]").length === 8'), 'eight running instance tabs');
    const tabs = await ui(`(() => { const t=document.querySelector('#tabs'),s=document.querySelector('#tabsShell'),r=document.querySelector('[data-tabs-scroll="1"]'); return {count:t.querySelectorAll('[data-tab]').length, overflow:t.scrollWidth>t.clientWidth, shell:s.classList.contains('has-overflow'), rightVisible:getComputedStyle(r).display!=='none'}; })()`);
    assert.deepEqual(tabs, { count: 8, overflow: true, shell: true, rightVisible: true });
    await ui(`document.querySelector('[data-tabs-scroll="1"]').click()`);
    await wait(() => ui('document.querySelector("#tabs").scrollLeft > 0'), 'tab scroll right');
    await ui(`document.querySelector('[data-tabs-scroll="-1"]').click()`);
    const lastId=controller.store.list().at(-1).id;
    const fullyVisible=id=>ui(`(()=>{const b=document.querySelector('[data-tab="${id}"]')?.closest('.tab');if(!b)return false;const box=document.querySelector('#tabs').getBoundingClientRect(),r=b.getBoundingClientRect();return r.left>=box.left-1&&r.right<=box.right+1;})()`);
    for(const width of [960,1280,1440]){window.setSize(width,900);await ui(`route('browser',${JSON.stringify(lastId)})`);await wait(()=>fullyVisible(lastId),'selected instance visible at '+width);const scrolled=await ui('document.querySelector("#tabs").scrollLeft');controller.emit();await new Promise(r=>setTimeout(r,100));assert(Math.abs(await ui('document.querySelector("#tabs").scrollLeft')-scrolled)<=1,'state repaint preserves instance scroll');}
    const screenshots = [];
    for (const theme of ['light', 'dark']) {
      await ui(`document.documentElement.dataset.theme='${theme}'`);
      await new Promise(resolve => setTimeout(resolve, 100));
      const file = path.join(root, `instance-tabs-${theme}.png`);
      fs.writeFileSync(file, (await window.webContents.capturePage()).toPNG());
      assert(fs.statSync(file).size > 1000);
      screenshots.push(file);
    }
    await ui('document.querySelector("#newTab").click()');
    await wait(() => ui(`!!document.querySelector('[data-new-env="random"]')`), 'new environment control');
    assert.equal(await ui(`(() => { document.querySelector('[data-new-env="random"]').click(); return document.querySelector('#modal [data-action="confirm"]').disabled; })()`), true, 'creation is blocked while random preset is pending');
    await wait(() => ui(`document.querySelector('#newEnvironmentSummary').textContent.includes('固定种子已生成')`), 'random environment result');
    const firstSeed = await ui('modal.newEnvironment.fingerprint.seed');
    await ui(`document.querySelector('[data-new-env="native"]').click()`);
    assert.equal(await ui('modal.newEnvironment'), null);
    await ui(`document.querySelector('[data-new-env="random"]').click()`);
    await wait(() => ui(`!!modal.newEnvironment && !modal.newEnvironmentBusy`), 'second random environment');
    assert.notEqual(await ui('modal.newEnvironment.fingerprint.seed'), firstSeed);
    assert.equal(await ui(`getComputedStyle(document.querySelector('.new-environment-plan>p')).whiteSpace`), 'normal');
    await new Promise(resolve => setTimeout(resolve, 150));
    const modalFile = path.join(root, 'new-instance-random.png');
    fs.writeFileSync(modalFile, (await window.webContents.capturePage()).toPNG());
    screenshots.push(modalFile);
    await ui("document.querySelector('#nameInput').value='随机环境实例'; document.querySelector('#startNew').checked=false; document.querySelector('#timezoneNew').checked=false; document.querySelector('#modal [data-action=confirm]').click()");
    await wait(() => controller.store.list().some(x => x.name === '随机环境实例'), 'created instance');
    const created = controller.store.list().find(x => x.name === '随机环境实例');
    assert.equal(created.environment.fingerprint.enabled, true);
    assert.equal(typeof created.environment.fingerprint.seed, 'string');
    assert(created.environment.fingerprint.seed.length > 0);
    const reloaded = new Store(root).get(created.id);
    assert.equal(reloaded.environment.fingerprint.seed, created.environment.fingerprint.seed);
    await ui("route('global')");
    await wait(() => ui("!!document.querySelector('.github-support-card')"), 'GitHub support card');
    assert.equal(await ui("document.querySelector('.github-repo-url').textContent"), 'github.com/HEYD66/facet');
    await ui("document.querySelector('.github-star-btn').click()");
    await wait(() => openedExternal.length === 1, 'GitHub external link');
    assert.equal(openedExternal[0], 'https://github.com/HEYD66/facet');
    const githubScreenshot = path.join(root, 'github-app-info.png');
    fs.writeFileSync(githubScreenshot, (await window.webContents.capturePage()).toPNG());
    assert(fs.statSync(githubScreenshot).size > 1000);
    controller.store.update(created.id, { url });
    await controller.start(created.id);
    const wc = controller.runtimes.get(created.id).view.webContents;
    await wait(() => wc.getURL() === url && !wc.isLoading(), 'local page loaded with generated environment');
    const applied = await wc.executeJavaScript(`(() => { const c=document.createElement('canvas'),gl=c.getContext('webgl'),debug=gl?.getExtension('WEBGL_debug_renderer_info'); return {platform:navigator.platform,threads:navigator.hardwareConcurrency,renderer:debug?gl.getParameter(debug.UNMASKED_RENDERER_WEBGL):null,canvas:document.createElement('canvas').toDataURL().length}; })()`);
    assert.equal(applied.platform, created.environment.platform);
    assert.equal(applied.threads, created.environment.cpu);
    assert(applied.canvas > 100);
    assert.equal(applied.renderer, created.environment.fingerprint.renderer);
    await controller.stop(created.id);
    await controller.start(created.id);
    const restartedWC = controller.runtimes.get(created.id).view.webContents;
    await wait(() => restartedWC.getURL() === url && !restartedWC.isLoading(), 'local page after instance restart');
    assert.equal(await restartedWC.executeJavaScript('navigator.hardwareConcurrency'), created.environment.cpu);
    await controller.stop(created.id);
    for (let i = controller.store.list().length; i < 15; i++) controller.store.create(`实例 ${i + 1}`);
    for (const instance of controller.store.list()) if (controller.runtimes.get(instance.id)?.status !== 'running') { controller.store.update(instance.id, { url }); await controller.start(instance.id); }
    controller.emit();
    await wait(() => ui('document.querySelectorAll("#tabs [data-tab]").length === 15'), 'fifteen running instance tabs');
    const fifteenthId = controller.store.list().at(-1).id;
    window.setSize(960, 900);
    await ui(`route('browser', '${fifteenthId}')`);
    await wait(() => fullyVisible(fifteenthId), 'complete fifteenth tab');
    screenshots.push(githubScreenshot);
    console.log(JSON.stringify({ passed: true, tabs: [8, 15], widths: [960, 1280, 1440], persisted: true, restarted: true, github: openedExternal[0], randomTemplate: created.environment.fingerprint.template, applied, screenshots }));
    server.close();
    await controller.closeAll(); window.destroy(); app.quit();
  } catch (error) {
    server?.close();
    console.error(error.stack || error.message);
    try { await controller?.closeAll(); } catch {}
    window?.destroy(); app.exit(1);
  }
});
